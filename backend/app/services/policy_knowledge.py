def is_policy_question(question: str) -> bool:
    """识别公开平台规则咨询；具体订单执行请求仍交给业务动作链路。"""
    text = re.sub(r"\s+", "", (question or "")).lower()
    if not text or any(marker in text for marker in POLICY_EXECUTION_MARKERS):
        return False
    direct_service = ("帮我催", "催一下", "还没发货", "支付失败", "付款失败", "还没到账", "没到账", "马上退款", "直接退款", "申请退款", "申请退货", "申请换货", "金额不一样", "价格不对", "少了一件", "少发", "有杂音", "质量有问题", "描述不一样", "与描述不符", "没照片", "没有照片")
    if any(marker in text for marker in direct_service):
        return False
    has_topic = any(topic in text for topic in POLICY_TOPICS)
    has_marker = any(marker in text for marker in POLICY_QUESTION_MARKERS)
    return has_topic and (
        has_marker
        or text in {"七天无理由", "运费险", "价保", "售后政策", "退款规则", "退货规则"}
    )


@dataclass(frozen=True)
class PolicySection:
    title: str
    content: str


@lru_cache(maxsize=1)
def load_policy_sections() -> list[PolicySection]:
    if not POLICY_FILE.exists():
        return []
    text = POLICY_FILE.read_text(encoding="utf-8")
    parts = re.split(r"\n## ", text)
    sections: list[PolicySection] = []
    for part in parts[1:]:
        title, _, body = part.partition("\n")
        content = re.sub(r"\s+", " ", body).strip()
        if title.strip() and content:
            sections.append(PolicySection(title=title.strip(), content=content))
    return sections


def _score(question: str, section: PolicySection) -> int:
    score = 0
    aliases = ALIASES.get(section.title, [])
    for word in aliases:
        if word and word in question:
            score += 6
    for token in re.findall(r"[\u4e00-\u9fa5]{2,}|[A-Za-z0-9]+", question):
        if token in section.title:
            score += 3
        if token in section.content:
            score += 1
    return score


def retrieve_policy(question: str, limit: int = 3) -> list[PolicySection]:
    ranked = [(section, _score(question, section)) for section in load_policy_sections()]
    ranked = [(section, score) for section, score in ranked if score > 0]
    ranked.sort(key=lambda item: item[1], reverse=True)
    return [section for section, _ in ranked[:limit]]


